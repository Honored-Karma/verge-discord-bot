/**
 * Получает дополнительные пользовательские фразы из базы данных, если она подключена.
 */
export async function getCustomRoasts() {
    try {
        const db = getDB();
        if (!db) return [];
        const items = await db.collection('custom_roasts').find({}).toArray();
        return items.map(item => item.text).filter(Boolean);
    } catch {
        return [];
    }
}

/**
 * Выбирает случайный элемент из массива при помощи криптостойкого RNG.
 */
function pickRandom(array) {
    if (!array || array.length === 0) return '';
    const index = randomInt(0, array.length);
    return array[index];
}

/**
 * Генерирует готовое сообщение прожарки с учетом ролей (сам себя, друга или бота).
 *
 * @param {Object} options
 * @param {string} options.callerId - ID того, кто вызвал команду
 * @param {string} options.targetId - ID того, кого прожаривают
 * @param {string} [options.botId] - ID клиента бота
 * @param {number} [options.pingMs] - Задержка WebSocket в миллисекундах
 * @param {Array<string>} [options.extraRoasts] - Дополнительные фразы
 * @returns {string} Готовое сообщение с пингом и смайликами
 */
export function generateRoastMessage({
    callerId,
    targetId,
    botId = null,
    pingMs = 0,
    extraRoasts = []
}) {
    const isBot = Boolean(botId && targetId === botId);
    const isSelf = targetId === callerId;

    const callerMention = `<@${callerId}>`;
    const targetMention = `<@${targetId}>`;

    let template = '';

    if (isBot) {
        template = pickRandom(BOT_ROASTS);
    } else if (isSelf) {
        const pool = extraRoasts.length > 0 ? [...SELF_ROASTS, ...extraRoasts] : SELF_ROASTS;
        template = pickRandom(pool);
    } else {
        const pool = extraRoasts.length > 0 ? [...TARGET_ROASTS, ...extraRoasts] : TARGET_ROASTS;
        template = pickRandom(pool);
    }

    const body = template
        .replaceAll('{ping}', targetMention)
        .replaceAll('{caller}', callerMention);

    const safePing = Number.isFinite(pingMs) && pingMs >= 0 ? Math.round(pingMs) : 0;
    const pingComment = pickRandom(PING_COMMENTS);
    const footer = `-# 📡 Пинг бота: ${safePing}мс · ${pingComment}`;

    return `${body}\n\n${footer}`;
}
